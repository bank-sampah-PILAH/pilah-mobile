import 'dart:io';

/// The one place the design ratchets' file-scanning rule lives.
///
/// Every guard under `test/design/` walks `lib/` looking for a pattern that
/// belongs to the design kit, and each one used to open that walk with the same
/// four lines. One of those lines is a trap: `Directory.listSync` yields paths
/// with the **platform** separator, so a path compared against a forward-slash
/// prefix such as `'lib/design/'` matches nothing at all on Windows. A guard
/// whose prefix never matches does not fail loudly — it silently stops
/// exempting the design kit itself and reports the very files it was written to
/// leave alone. Thirteen of them did exactly that on every branch, which made a
/// local `flutter test` useless for predicting CI.
///
/// Copied into sixteen files, that rule was sixteen chances to get it wrong
/// again. It is one function now, and each guard keeps only the exemptions that
/// are its own policy rather than a shared fact about paths.
Iterable<DesignSource> designSources([Directory? root]) sync* {
  final dir = root ?? Directory('lib');
  final rootPath = _forwardSlashes(dir.path);
  for (final entity in dir.listSync(recursive: true)) {
    if (entity is! File || !entity.path.endsWith('.dart')) continue;
    yield DesignSource._(_forwardSlashes(entity.path), rootPath, entity);
  }
}

/// One Dart source under the scanned root, with its path already normalized.
class DesignSource {
  const DesignSource._(this.path, this.rootPath, this._file);

  /// The path as the guards report it, always with forward slashes.
  final String path;

  /// The root the walk started from, normalized the same way.
  final String rootPath;

  final File _file;

  /// The path below [rootPath], so a guard reads the same under `lib/` as it
  /// does under the temporary directory its own unit test builds.
  String get relativePath => path.substring(rootPath.length + 1);

  /// Inside the design kit, which is what most guards exempt: the kit is where
  /// the raw widget is allowed to be used.
  bool get inDesignKit => relativePath.startsWith('design/');

  /// Generated by build_runner, so nobody chose what is in it.
  bool get isGenerated =>
      path.endsWith('.g.dart') || path.endsWith('.freezed.dart');

  String read() => _file.readAsStringSync();
}

String _forwardSlashes(String path) => path.replaceAll(r'\', '/');
